package com.waiterapp.data.local

/**
 * Абстракция над хранилищем сессии официанта. Выделена в интерфейс, чтобы:
 * 1) репозитории не зависели от Android Context напрямую;
 * 2) в юнит-тестах можно было подставить простой fake вместо
 *    EncryptedSharedPreferences (которому нужен реальный Android runtime).
 *
 * Сервер при логине (POST api/v1/worker/auth/logIn) выдаёт ДВА токена:
 *  - accessToken   - используется в заголовке "Authorization: Bearer ..."
 *                    для КАЖДОГО запроса к API (см. AuthInterceptor).
 *  - autoLoginToken (поле "token" в ответе сервера) - долгоживущий токен
 *                    для автоматического входа. Действует 24 часа с
 *                    момента получения: пока это время не истекло,
 *                    официант при повторном открытии приложения попадает
 *                    сразу в аккаунт, без повторного ввода staffId/пароля.
 *                    На 25-й час токен считается просроченным - сессия
 *                    автоматически очищается, и нужно войти заново.
 */
interface TokenStore {

    /** Результат проверки сессии при старте приложения. */
    enum class SessionState {
        /** Есть НЕ истёкший (моложе 24ч) autoLoginToken - можно войти автоматически. */
        LOGGED_IN,
        /** Сохранённой сессии нет вовсе (обычный экран входа, без сообщений). */
        LOGGED_OUT,
        /** Сессия БЫЛА, но 24 часа истекли - только что очищена автоматически. */
        EXPIRED
    }

    fun saveSession(accessToken: String, autoLoginToken: String, staffId: Long)

    /** Токен для заголовка Authorization (используется на каждый запрос). */
    fun getAccessToken(): String?

    /** Долгоживущий токен авто-входа (НЕ используется как Bearer-заголовок). */
    fun getAutoLoginToken(): String?

    fun getStaffId(): Long?

    /** Момент первоначального ручного логина, с которого считается 24-часовая сессия. */
    fun getSessionStartedAt(): Long?

    /** Атомарно заменяет только accessToken, не продлевая 24-часовую сессию. */
    fun updateAccessToken(accessToken: String)

    /** true, если есть НЕ истёкший autoLoginToken. */
    fun isLoggedIn(): Boolean

    /**
     * Полная проверка сессии для стартового экрана приложения.
     * Если найден просроченный (>24ч) токен - сама очищает хранилище
     * (см. clearSession) и возвращает EXPIRED, чтобы вызывающий код мог
     * показать официанту понятное сообщение вместо пустого экрана входа.
     */
    fun checkSession(): SessionState

    fun clearSession()

    // Ник официанта - пока в документации API нет отдельного эндпоинта
    // профиля/логина, который бы возвращал имя, поэтому официант вводит
    // его сам на экране входа, и он хранится только локально на устройстве.
    fun saveStaffName(name: String)
    fun getStaffName(): String?
}
