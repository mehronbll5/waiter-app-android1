package com.waiterapp.data.network

/**
 * Единая точка настройки подключения к серверу.
 *
 * Бэкенд - Spring Boot приложение (см. application.yml на сервере),
 * поднимается на порту 8081, все пути начинаются с "api/v1/...".
 *
 * ВАЖНО: поставь сюда реальный адрес твоего сервера:
 * - если тестируешь на Android-эмуляторе, а бэкенд крутится на этом же
 *   компьютере -> "http://10.0.2.2:8081/" (специальный алиас эмулятора
 *   для localhost хост-машины, обычный "localhost" внутри эмулятора
 *   указывает на сам эмулятор, а не на твой компьютер);
 * - если тестируешь на реальном телефоне в той же Wi-Fi сети ->
 *   "http://<локальный IP компьютера>:8081/" (например "http://192.168.1.50:8081/");
 * - если сервер выложен наружу (ngrok/домен) -> используй этот адрес,
 *   обязательно https и со слэшем на конце.
 */
object ApiConfig {

    // ВРЕМЕННО: тестируем напрямую по локальной сети (ноутбук с бэкендом +
    // телefon на его же Wi-Fi/раздаче), без ngrok. Когда снова понадобится
    // ngrok (доступ из другой сети/интернета) - верни https-адрес обратно и
    // не забудь про слэш на конце.
    const val BASE_URL = "    "

    /**
     * Адрес для "сырого" WebSocket-транспорта STOMP-эндпоинта.
     * Бэкенд регистрирует его как registry.addEndpoint("/ws").withSockJS() -
     * "/websocket" на конце это не опечатка, а способ подключиться напрямую
     * по WebSocket, минуя полноценный протокол SockJS (нужен только для
     * браузеров без поддержки WebSocket, для Android он не нужен).
     */
    val WS_URL: String
        get() {
            val wsScheme = when {
                BASE_URL.startsWith("https://") -> "wss://" + BASE_URL.removePrefix("https://")
                BASE_URL.startsWith("http://") -> "ws://" + BASE_URL.removePrefix("http://")
                else -> BASE_URL
            }
            return wsScheme.trimEnd('/') + "/ws/websocket"
        }

    // ==========================================================================
    // ДЕМО-РЕЖИМ БЕЗ БЭКЕНДА - главный флаг. Включает полностью автономную
    // работу приложения: любой логин/пароль пускает внутрь, Столы/Меню/Заказы
    // работают на встроенных тестовых данных, ни один экран не делает
    // настоящих сетевых запросов и не может зависнуть/показать ошибку сети.
    // Нужен, например, чтобы показать логику и UI приложения другому
    // разработчику (в т.ч. iOS) без поднятого бэкенда.
    //
    // Чтобы вернуть работу с реальным сервером - поставь false.
    // ==========================================================================
    const val DEMO_MODE_ENABLED = false

    // ВРЕМЕННЫЕ тестовые режимы (без реального сервера) - на случай, если
    // бэкенд временно недоступен и нужно проверить экраны на моках.
    // Держи выключенными (false), когда сервер поднят и доступен.
    // Пока DEMO_MODE_ENABLED = true, эти два всегда фактически включены
    // (см. геттеры ниже), независимо от того, что тут написано руками.
    private const val MOCK_LOGIN_ENABLED_RAW = false
    private const val MOCK_MENU_ENABLED_RAW = false
    val MOCK_LOGIN_ENABLED: Boolean get() = DEMO_MODE_ENABLED || MOCK_LOGIN_ENABLED_RAW
    val MOCK_MENU_ENABLED: Boolean get() = DEMO_MODE_ENABLED || MOCK_MENU_ENABLED_RAW

    // ВРЕМЕННО: автоматический вход тестовым официантом при каждом запуске
    // приложения, чтобы не набирать вручную staffId/пароль на экране входа.
    // Логин по-прежнему идёт на настоящий сервер (не мок) - просто данные
    // подставляются автоматически, экран входа не показывается.
    // Чтобы вернуть обычный вход - поставь false (или удали этот блок).
    const val DEV_AUTO_LOGIN_ENABLED = false
    const val DEV_STAFF_ID = 999999999L
    const val DEV_PASSWORD = "Admin123"

    // ВРЕМЕННО: подставить готовый accessToken напрямую, без похода на
    // /logIn (например, если токен прислал бэкенд-разработчик). accessToken
    // его срок определяется jwt.access-expiration на сервере - когда протухнет,
    // сюда нужно вставить новый и пересобрать.
    const val DEV_TOKEN_ENABLED = false
    const val DEV_ACCESS_TOKEN = "ВСТАВЬ_СЮДА_ACCESS_TOKEN"

    // ВРЕМЕННО: вход по уже готовому refresh-токену (поле "token" из ответа
    // /logIn), полученному от бэкенд-разработчика - без ввода staffId/пароля.
    // При старте приложение само сходит с этим токеном на
    // /api/v1/worker/auth/auto и получит СВЕЖИЙ accessToken + имя официанта,
    // так что, в отличие от DEV_TOKEN_ENABLED, пересобирать APK каждые
    // accessToken не обновляется по таймеру: refresh выполняется только после 401.
    // autoLoginToken используется для получения нового accessToken.
    const val DEV_REFRESH_TOKEN_ENABLED = false
    const val DEV_REFRESH_TOKEN = "6068f374-4467-4c60-9aa2-b7275830e3c2"

    // ВРЕМЕННО: полностью пропускать экран входа (без попытки логина вообще)
    // и сразу открывать "Карту зала". Токена при этом НЕТ, поэтому запросы
    // к бэкенду, требующие авторизации (Столы/Меню/Заказы), будут отвечать
    // 401/403, пока не залогинишься валидным пользователем. Нужно только
    // чтобы посмотреть UI Карты зала без сервера/логина.
    // Чтобы вернуть обычный вход - поставь false (или удали этот блок).
    const val SKIP_LOGIN_ENABLED = false
}
